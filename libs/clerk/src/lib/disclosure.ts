/**
 * The Clerk data-use disclosure (AI-13): versioned Markdown in libs/clerk/disclosure/disclosure@N.md,
 * compiled into @materia/domain (clerk-disclosure.generated.ts) so the web app shows it and the
 * gateway knows the current version. Owners and admins acknowledge it before Clerk's first use; a
 * new version needs acknowledging again.
 */

/** `disclosure@3` → 3. */
export function disclosureVersion(name: string): number {
  const match = /^disclosure@([1-9]\d*)$/.exec(name);
  if (!match?.[1]) throw new Error(`Disclosure file "${name}.md" must be named disclosure@<version>.md`);
  return Number(match[1]);
}

/** The generated module: every version's text, and the newest version. */
export function generateDisclosureModule(files: { name: string; content: string }[]): string {
  const versions = files
    .map((file) => ({ version: disclosureVersion(file.name), content: file.content.trim() }))
    .sort((a, b) => a.version - b.version);
  if (!versions.length) throw new Error('No Clerk disclosure found in libs/clerk/disclosure');
  versions.forEach((entry, index) => {
    if (entry.version !== index + 1) throw new Error(`Clerk disclosure versions must run 1..N (missing ${index + 1})`);
    if (!entry.content) throw new Error(`Clerk disclosure ${entry.version} is empty`);
  });
  const entries = versions.map((entry) => `  ${entry.version}: ${JSON.stringify(entry.content)},`).join('\n');
  return [
    '// Generated by `pnpm materia-scripts clerk-prompts` from libs/clerk/disclosure/*.md. Do not edit.',
    '/** The current Clerk data-use disclosure; an org must acknowledge it before Clerk runs (AI-13). */',
    `export const CLERK_DISCLOSURE_VERSION = ${versions.length};`,
    '',
    '/** Each version of the disclosure, as Markdown. */',
    'export const CLERK_DISCLOSURES: Readonly<Record<number, string>> = {',
    entries,
    '};',
    '',
  ].join('\n');
}
