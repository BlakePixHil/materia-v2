import { ClerkDraftTypeSchema, type ClerkDraftType } from '@materia/domain';

/**
 * The letter types Clerk drafts (AI-10, ADR-050): one JSON file each in libs/clerk/drafts,
 * compiled into @materia/domain (clerk-draft-types.generated.ts) so the web app offers them and
 * Functions draft them. Each file is validated here, so a broken type fails the compile.
 */

/** Every type parsed, ordered by title with the general letter (`needsInstructions`) last. */
export function parseDraftTypes(files: readonly { name: string; content: string }[]): ClerkDraftType[] {
  const types = files.map((file) => {
    let json: unknown;
    try {
      json = JSON.parse(file.content);
    } catch (error) {
      throw new Error(`Draft type ${file.name}.json isn't valid JSON: ${(error as Error).message}`);
    }
    const parsed = ClerkDraftTypeSchema.safeParse(json);
    if (!parsed.success)
      throw new Error(
        `Draft type ${file.name}.json is invalid: ${parsed.error.issues
          .map((issue) => `${issue.path.join('.') || '(root)'} ${issue.message}`)
          .join('; ')}`,
      );
    if (parsed.data.id !== file.name)
      throw new Error(`Draft type ${file.name}.json must have "id": "${file.name}" (it has "${parsed.data.id}")`);
    return parsed.data;
  });
  if (!types.length) throw new Error('No Clerk draft types found in libs/clerk/drafts');
  return types.sort(
    (a, b) => Number(!!a.needsInstructions) - Number(!!b.needsInstructions) || a.title.localeCompare(b.title),
  );
}

/** The generated module: the registry, in picker order. */
export function generateDraftTypesModule(files: readonly { name: string; content: string }[]): string {
  const types = parseDraftTypes(files);
  return [
    '// Generated by `pnpm materia-scripts clerk-prompts` from libs/clerk/drafts/*.json. Do not edit.',
    "import type { ClerkDraftType } from './clerk-drafts';",
    '',
    '/** The letter types Clerk drafts (AI-10), in picker order. The wording guidance is illustrative (AI-10a). */',
    `export const CLERK_DRAFT_TYPES: readonly ClerkDraftType[] = ${JSON.stringify(types, null, 2)};`,
    '',
  ].join('\n');
}
