/**
 * `materia-scripts env --env <dev|staging|prod>`: writes apps/web/src/environments/environment.<env>.ts
 * from the Terraform outputs of that environment (FND-03). The Firebase web config is not secret.
 *
 *   pnpm materia-scripts env --env dev                    # runs `terraform output -json` in infra/terraform
 *   pnpm materia-scripts env --env dev --from out.json    # or reads a saved `terraform output -json`
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

export const ENVS = ['dev', 'staging', 'prod'] as const;
export type EnvName = (typeof ENVS)[number];

export interface FirebaseWebConfig {
  projectId: string;
  appId: string;
  apiKey: string;
  authDomain: string;
  storageBucket: string;
  messagingSenderId: string;
  measurementId?: string;
}

const REQUIRED_KEYS = ['projectId', 'appId', 'apiKey', 'authDomain', 'storageBucket', 'messagingSenderId'] as const;
const WORKSPACE_ROOT = path.resolve(import.meta.dirname, '../../..');

/** Extracts and validates the web config from `terraform output -json`. */
export function parseTerraformOutputs(raw: string): FirebaseWebConfig {
  const outputs = JSON.parse(raw) as Record<string, { value?: unknown } | undefined>;
  const value = outputs['web_app_config']?.value;
  if (typeof value !== 'string') throw new Error('terraform output has no web_app_config (string) value');
  const parsed = JSON.parse(value) as Record<string, unknown>;

  const config: Record<string, string> = {};
  for (const key of REQUIRED_KEYS) {
    const field = parsed[key];
    if (typeof field !== 'string' || field.length === 0) throw new Error(`web_app_config.${key} is missing`);
    config[key] = field;
  }
  const measurementId = parsed['measurementId'];
  return {
    ...(config as Omit<FirebaseWebConfig, 'measurementId'>),
    ...(typeof measurementId === 'string' && measurementId ? { measurementId } : {}),
  };
}

/** Renders the Angular environment file. Output is deterministic so regenerating is a no-op. */
export function renderEnvironment(env: EnvName, config: FirebaseWebConfig): string {
  const firebase = JSON.stringify(config, null, 2).replace(/\n/g, '\n  ');
  return [
    `// Generated by \`pnpm materia-scripts env --env ${env}\` from Terraform outputs. Do not edit.`,
    '// The Firebase web config is public by design; access is enforced by rules and App Check.',
    'export const environment = {',
    `  name: '${env}',`,
    `  useEmulators: false,`,
    `  firebase: ${firebase},`,
    '} as const;',
    '',
  ].join('\n');
}

export function environmentPath(env: EnvName): string {
  return path.join(WORKSPACE_ROOT, 'apps/web/src/environments', `environment.${env}.ts`);
}

function isEnv(value: string | undefined): value is EnvName {
  return ENVS.some((env) => env === value);
}

export async function main(argv: string[] = process.argv.slice(2)): Promise<void> {
  const { values } = parseArgs({
    args: argv,
    options: {
      env: { type: 'string' },
      from: { type: 'string' },
      'tf-dir': { type: 'string', default: path.join(WORKSPACE_ROOT, 'infra/terraform') },
    },
  });
  if (!isEnv(values.env)) throw new Error(`--env must be one of ${ENVS.join(', ')}`);

  const raw = values.from
    ? readFileSync(values.from, 'utf8')
    : execFileSync('terraform', ['output', '-json'], { cwd: values['tf-dir'], encoding: 'utf8' });
  const file = environmentPath(values.env);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, renderEnvironment(values.env, parseTerraformOutputs(raw)));
  console.log(`Wrote ${path.relative(WORKSPACE_ROOT, file)}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err: unknown) => {
    console.error(err instanceof Error ? err.message : err);
    process.exitCode = 1;
  });
}
